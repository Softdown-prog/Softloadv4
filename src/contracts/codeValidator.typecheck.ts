import { validateCode, validateCss, validateJs, validateXml, extractCodeBlocks, validateResponseBlocks } from '../core/codeValidator';
import type { CodeValidationResult, ResponseCodeValidation, ExtractedCodeBlock, SupportedCodeLanguage } from '../core/codeValidator';
const lang: SupportedCodeLanguage = 'xml';
const code: CodeValidationResult = validateCode('<x/>', lang);
const css: CodeValidationResult = validateCss('.x {color: red}');
const js: CodeValidationResult = validateJs('const x = 1');
const xml: CodeValidationResult = validateXml('<x/>');
const blocks: ExtractedCodeBlock[] = extractCodeBlocks('texto');
const response: ResponseCodeValidation = validateResponseBlocks('texto');
void code; void css; void js; void xml; void blocks; void response;
